import hashlib
import json
import os
import re
import shutil
from datetime import datetime, timezone
from pathlib import Path
from app.config import settings


class StorageManager:
    @staticmethod
    def sanitize_name(name: str) -> str:
        """
        Sanitizes names for safe filesystem path usage, preventing directory traversal.
        """
        clean = re.sub(r"[^a-zA-Z0-9_\-]", "_", name)
        return clean or "default"

    @staticmethod
    def calculate_sha256(file_path: Path) -> str:
        h = hashlib.sha256()
        with open(file_path, "rb") as f:
            while chunk := f.read(65536):
                h.update(chunk)
        return h.hexdigest()

    @staticmethod
    def delete_job_files(job_id: str, source_file_path: str | None = None) -> dict[str, int]:
        """Delete every server-side artifact owned by a job.

        Job IDs are generated by the backend, but the sanitized value is still
        used for globbing so this cleanup can never escape the managed storage
        roots. The optional database path is accepted only when it resolves
        below one of those roots.
        """
        safe_job_id = StorageManager.sanitize_name(job_id)
        dataset_dir = settings.dataset_path.resolve()
        storage_dir = Path(settings.BASE_STORAGE_DIR).resolve()
        temp_dir = settings.temp_path.resolve()
        managed_roots = (dataset_dir, storage_dir, temp_dir)
        candidates: set[Path] = set()

        candidates.add(dataset_dir / "metadata" / f"{safe_job_id}.json")
        candidates.update(path for path in dataset_dir.rglob(f"{safe_job_id}_*") if path.is_file() or path.is_symlink())

        for root in {storage_dir, temp_dir}:
            if root.exists():
                candidates.update(path for path in root.rglob(f"{safe_job_id}*") if path.is_file() or path.is_symlink())

        if source_file_path:
            source_path = Path(source_file_path).resolve(strict=False)
            if any(source_path == root or root in source_path.parents for root in managed_roots):
                candidates.add(source_path)

        deleted_files = 0
        deleted_bytes = 0
        for path in candidates:
            try:
                resolved = path.resolve(strict=False)
                if not any(resolved == root or root in resolved.parents for root in managed_roots):
                    continue
                if path.is_file() or path.is_symlink():
                    try:
                        deleted_bytes += path.stat().st_size
                    except OSError:
                        pass
                    path.unlink(missing_ok=True)
                    deleted_files += 1
            except OSError:
                # A worker may have removed the same temporary artifact while
                # cancellation was being processed. The final sweep is idempotent.
                continue

        # Remove category directories left empty by the purge. Metadata itself
        # is retained as a directory because future jobs reuse it.
        for directory in sorted(
            (path for path in dataset_dir.rglob("*") if path.is_dir()),
            key=lambda path: len(path.parts),
            reverse=True,
        ):
            if directory.name == "metadata":
                continue
            try:
                directory.rmdir()
            except OSError:
                pass

        return {"deleted_files": deleted_files, "deleted_bytes": deleted_bytes}

    @staticmethod
    def store_segment_files(
        job_id: str,
        segment_id: str,
        temp_segment_path: Path,
        category_ids: list[str],
    ) -> list[str]:
        """
        Distributes extracted segment file to each category folder under dataset/.
        Uses hardlinks when supported, falling back to copy.
        Returns list of stored relative file paths.
        """
        dataset_dir = settings.dataset_path
        stored_paths: list[str] = []

        safe_job_id = StorageManager.sanitize_name(job_id)
        safe_seg_id = StorageManager.sanitize_name(segment_id)
        file_name = f"{safe_job_id}_{safe_seg_id}.mp4"

        categories = category_ids or ["uncategorized"]

        first_dest: Path | None = None

        for cat_id in categories:
            safe_cat_id = StorageManager.sanitize_name(cat_id)
            cat_dir = dataset_dir / safe_cat_id
            cat_dir.mkdir(parents=True, exist_ok=True)
            target_path = cat_dir / file_name

            target_path.unlink(missing_ok=True)

            if first_dest is None:
                # Copy or move from temp
                shutil.copy2(temp_segment_path, target_path)
                first_dest = target_path
            else:
                # Hardlink or copy if hardlink unsupported
                try:
                    os.link(first_dest, target_path)
                except (OSError, NotImplementedError):
                    shutil.copy2(first_dest, target_path)

            stored_paths.append(str(target_path.relative_to(dataset_dir.parent)))

        # Clean up temporary cut file
        temp_segment_path.unlink(missing_ok=True)
        return stored_paths

    @staticmethod
    def save_job_metadata(
        job_id: str,
        page_url: str,
        media_url: str,
        media_type: str,
        quality: dict,
        source_duration: float | None,
        segment_records: list[dict],
        categories_metadata: list[dict] | None = None,
        errors: list[str] | None = None,
    ) -> Path:
        """
        Writes complete traceable CVAT-ready metadata JSON to dataset/metadata/<job_id>.json
        """
        safe_job_id = StorageManager.sanitize_name(job_id)
        metadata_dir = settings.dataset_path / "metadata"
        metadata_dir.mkdir(parents=True, exist_ok=True)
        meta_file = metadata_dir / f"{safe_job_id}.json"

        data = {
            "schema_version": "1.0",
            "job_id": job_id,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "source": {
                "page_url": page_url,
                "media_url": media_url,
                "media_type": media_type,
                "duration_seconds": source_duration,
            },
            "selected_quality": quality,
            "categories_metadata": categories_metadata or [],
            "segments_count": len(segment_records),
            "segments": segment_records,
            "processing_errors": errors or [],
        }

        with open(meta_file, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)

        return meta_file
